#!/usr/bin/env node
// Emits importable n8n workflow JSON into ./workflows.

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build as wf1 } from '../src/wf1-daily-scan.mjs';
import { TABS, QUEUE_COLUMNS } from '../src/schema.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'workflows');
mkdirSync(outDir, { recursive: true });

const targets = [
  ['01-daily-job-scan.json', wf1],
];

let total = 0;
for (const [file, build] of targets) {
  const wf = build();

  // Sanity: every connection endpoint must reference a real node.
  const names = new Set(wf.nodes.map((n) => n.name));
  for (const [from, conn] of Object.entries(wf.connections)) {
    if (!names.has(from)) throw new Error(`${file}: connection from unknown node "${from}"`);
    for (const out of conn.main) {
      for (const c of out) {
        if (!names.has(c.node)) throw new Error(`${file}: connection to unknown node "${c.node}"`);
      }
    }
  }

  writeFileSync(join(outDir, file), JSON.stringify(wf, null, 2) + '\n');
  total += wf.nodes.length;
  console.log(`${file.padEnd(28)} ${String(wf.nodes.length).padStart(2)} nodes`);
}

console.log(`${''.padEnd(28)} ${String(total).padStart(2)} nodes total`);

// --------------------------------------------------------------- schema guard
// The Sheets nodes map by column name. If "Build Queue Row" emits a key that is
// not a header in the sheet, that column is silently dropped — so assert here.
{
  const wf = wf1();
  const src = wf.nodes.find((n) => n.name === 'Build Queue Row').parameters.jsCode;
  // dedent() has already normalised indentation, so match any leading spaces.
  const body = src.slice(src.indexOf('return [{ json: {'));
  // Matches both `key: value` and ES6 shorthand `key,`.
  const emitted = [...body.matchAll(/^\s+(\w+)\s*[,:]/gm)].map((m) => m[1]);
  if (!emitted.length) throw new Error('Schema guard extracted no columns — the regex is stale.');

  // Routing flags consumed by the "Row Complete?" gate. They never reach the
  // sheet (the Sheets node maps by column name and ignores unknown keys).
  const CONTROL_FIELDS = ['row_valid', 'row_issues'];

  const missing = emitted.filter((k) => !QUEUE_COLUMNS.includes(k) && !CONTROL_FIELDS.includes(k));
  const unused = QUEUE_COLUMNS.filter((k) => !emitted.includes(k));

  if (missing.length) throw new Error(`Queue row emits columns absent from schema: ${missing}`);
  if (unused.length) throw new Error(`Schema declares columns the Queue row never sets: ${unused}`);
  console.log(`\nSchema guard: ${emitted.length} Queue columns match src/schema.mjs`);
}

// ------------------------------------------------------- Apps Script emitter
const gs = `// Auto-generated by scripts/build-workflows.mjs — do not edit by hand.
//
// Creates every tab this project needs, with exact headers.
// In your Google Sheet: Extensions -> Apps Script, paste this, press Run,
// and approve the one-time permission prompt.

var TABS = ${JSON.stringify(TABS, null, 2)};

function setUpJobsSheet() {
  var ss = SpreadsheetApp.getActiveSpreadsheet();

  Object.keys(TABS).forEach(function (name) {
    var headers = TABS[name];
    var sheet = ss.getSheetByName(name) || ss.insertSheet(name);

    sheet.getRange(1, 1, 1, headers.length).setValues([headers]);
    sheet.getRange(1, 1, 1, headers.length).setFontWeight('bold');
    sheet.setFrozenRows(1);

    // Trim stray columns so the Sheets node doesn't see blank headers.
    var extra = sheet.getMaxColumns() - headers.length;
    if (extra > 0) sheet.deleteColumns(headers.length + 1, extra);
  });

  // Remove the default empty sheet if it is still untouched.
  var def = ss.getSheetByName('Sheet1');
  if (def && ss.getSheets().length > 1 && def.getLastRow() === 0) ss.deleteSheet(def);

  SpreadsheetApp.getUi().alert('Done — ' + Object.keys(TABS).join(', ') + ' are ready.');
}
`;

writeFileSync(join(outDir, 'sheet-setup.gs'), gs);
console.log('sheet-setup.gs               Apps Script for tab creation');
